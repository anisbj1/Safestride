    offsets[0] = 0;
    for (uint32_t k = 1; k < 30; ++k) {
        offsets[k] = offsets[k - 1] + ((k % 2u == 1u) ? 500u : 1500u);
    }
    int late_windows = 0;
    int late_valid = 0;
    // Windows ending ≥12 s: the EARLIEST possible hold has always expired
    // by then (first plausible verdict ≈3 s, fresh-fails ≈5 s,
