void test_processor_beat_starvation_recovers() {
    // FIX loop 3 (bench round 3, hr_finger_round3_20261015.out): ONE early
    // transient was accepted as beats and seeded amp_ema_; the then-adaptive
    // threshold froze at 5080 for the whole 90 s run while pulse peaks
    // reached only 1875 → nab = 0, b = 0, no HR: a self-locking threshold
    // (amp_ema_ updated only on accepted beats, so it could never decay).
    // FIX loop 4 deleted that amplitude-coupled state entirely (ratchet
    // class gone by construction), so this fixture is RETAINED as the
    // regression guard for what it also exercises: an in-band artifact
    // burst must not permanently poison detection — the burst crests are
    // accepted as beats while it lasts (above the floor, outside the
    // refractory — the already-accepted noise trade), and the real 70 bpm
    // train must own every window after it ends.
    // Fixture: real-data DC + 70 bpm sine (AC peak 1500 → filtered peak
    // ≈ 1470), plus a rhythmic motion-artifact burst at t = 2 s: 1.5 Hz
    // sits in the middle of the 0.5–4 Hz passband, so the chain passes its
    // crests at ~unity — exactly the in-band transient class a finger
    // jostle produces.
    // Named fixture constants (see below): kBurstFreqHz, kBurstAmplitude,
    // kBurstStartMs, kBurstDurationMs.
    signal::SignalProcessor p;
    signal::SignalWindowOutput last{};
    int closed = 0;
    for (int sec = 0; sec < 60; ++sec) {
        const TimeMs base = static_cast<TimeMs>(sec) * signal::kMotionWindowMs;
        PpgSample ppg[100];
        for (uint32_t i = 0; i < 100; ++i) {
            const TimeMs t = base + i * signal::kPpgSamplePeriodMs;
            ppg[i] = mkPpg(t, kRealDataAcStrong, 70.0f / 60.0f, false, kRealDataDcIr);
            if (t >= kBurstStartMs && t < kBurstStartMs + kBurstDurationMs) {
                // rhythmic motion artifact, zero-mean: crests reach
                // 163 000 + 20 000 = 183 000 < 262 143 → no saturation.
                const float artifact =
                    kBurstAmplitude *
                    std::sin(2.0f * kTestPi * kBurstFreqHz * static_cast<float>(t - kBurstStartMs) /
                             static_cast<float>(signal::kMsPerSecond));
                ppg[i].ir = static_cast<uint32_t>(static_cast<int32_t>(ppg[i].ir) +
                                                  static_cast<int32_t>(artifact));
                ppg[i].red = ppg[i].ir;
            }
        }
        p.feedPpg(ppg, 100);
        ImuSample imu[50];
        for (uint32_t i = 0; i < 50; ++i) {
            imu[i] = mkQuietImu(base + i * signal::kImuSamplePeriodMs);
        }
        p.feedImu(imu, 50);
        closeDueWindows(p, base + signal::kMotionWindowMs + signal::kMaxSampleGapMs, last, closed);
    }
    TEST_ASSERT_TRUE(closed >= 55);
    // Beats resumed after the transient: the last window carries a full HR
    // lookback of real beats (frozen-threshold code yields 0 here).
    TEST_ASSERT_TRUE(last.ppg_beat_count >= signal::kMinBeatsForHr);
    TEST_ASSERT_TRUE(last.ppg.hr_valid);
    TEST_ASSERT_EQUAL(static_cast<int>(DataQuality::Good), static_cast<int>(last.ppg.quality));
    TEST_ASSERT_FLOAT_WITHIN(3.0f, 70.0f, last.ppg.hr_bpm);
    // The threshold IS the 0.1 % DC floor (≈ 163 at DC 163 k) since FIX
    // loop 4 — there is no amplitude-coupled bar left that the burst could
    // freeze (loop 3's bench freeze was 5080).
    TEST_ASSERT_TRUE(last.ppg_peak_threshold > 0.0f);
    TEST_ASSERT_TRUE(last.ppg_peak_threshold < 1200.0f);
    TEST_ASSERT_TRUE(last.ppg_peaks_above_threshold > 0u);
    printHrAccuracyRow(70.0f, last);
}

