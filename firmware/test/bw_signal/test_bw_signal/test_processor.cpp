constexpr float kTestPi = 3.14159265f;
constexpr float kTestDcIr = 50000.0f;           // plausible MAX30102 DC baseline
constexpr float kTestPulseAmplitude = 1000.0f;  // PI ≈ 1.4 % after filtering
// FIX loop 2b real-data golden (developer ground truth 2026-10-14, same
// wiring/sensor as the bracelet): DC ~163 000 counts (= the measured
// 2540 nA at the 4096 nA range) with pulsatile AC 500–2000 counts at
// 65–70 bpm — the band in which the tester reads BPM comfortably. AC here
// is the sine PEAK amplitude in counts (PI = ac_rms/dc = A/(sqrt(2)*dc)).
constexpr float kRealDataDcIr = 163000.0f;
constexpr float kRealDataAcWeak = 600.0f;     // weak end: PI ≈ 0.26 %
constexpr float kRealDataAcStrong = 1500.0f;  // clear pulse: PI ≈ 0.65 %
// FIX 2026-10-15 (hr_valid decoupling): below the tester's 500–2000 pulse
// band — PI = 300/(sqrt(2)*163000) ≈ 0.13 % ⇒ pi_factor 0.1 ⇒ quality stays
// Insufficient, yet the train is regular and detectable (filtered peak ≈ 294
// > the 0.1 % PI floor ≈ 163): the bench's weak-contact windows that must
// now read `HR ~70?` instead of `HR --`.
constexpr float kRealDataAcFaint = 300.0f;
// FIX loop 4 (jitter fixture): ±50 % beat-to-beat amplitude jitter about a
// 1200-count mean (the bench's real variability class, round 7) at DC
// 160 000 — mean PI ≈ 0.53 % (well above the floor, so quality would be
// Good if the beats were all detected; only detection may fail here).
constexpr float kJitterDcIr = 160000.0f;
constexpr float kJitterAmpHigh = 1800.0f;
constexpr float kJitterAmpLow = 600.0f;

// FIX loop 3 starvation fixture: rhythmic motion-artifact burst. 1.5 Hz
// sits mid-band in the 0.5–4 Hz passband (chain gain ≈ unity), so the
// detector sees its crests as giant beats — the in-band transient class
// that seeded amp_ema_ on the bench (round 3: thr frozen at 5080 while
// pulse peaks reached 1875). Amplitude keeps raw crests at 183 000
// counts < 262 143 → no saturation. Duration covers 4 crests (667 ms
// apart, all outside the 300 ms refractory), ending on a near-zero
// crossing so the chain has no large ring-down edge after the burst.
constexpr float kBurstFreqHz = 1.5f;
constexpr float kBurstAmplitude = 20000.0f;
constexpr TimeMs kBurstStartMs = 2000;
constexpr TimeMs kBurstDurationMs = 2333;

PpgSample mkPpg(TimeMs t, float pulse_amplitude, float freq_hz, bool saturated = false,
                float dc_ir = kTestDcIr) {
    PpgSample s{};
    s.t_ms = t;
    const float x =
        dc_ir + pulse_amplitude * std::sin(2.0f * kTestPi * freq_hz * static_cast<float>(t) /
                                           static_cast<float>(signal::kMsPerSecond));
    s.ir = static_cast<uint32_t>(x);
    s.red = s.ir;
    s.saturated = saturated;
    return s;
}

ImuSample mkQuietImu(TimeMs t) {
    ImuSample s{};
    s.t_ms = t;
    s.accel_g[0] = 0.0f;
    s.accel_g[1] = 0.0f;
    s.accel_g[2] = 1.0f;
    return s;
}

ImuSample mkMotionImu(TimeMs t) {
    // |a| = 1.5 g ⇒ ENMO 0.5 g, far above kMaxMotionForValidHrEnmoG.
    ImuSample s{};
    s.t_ms = t;
    s.accel_g[0] = 0.0f;
    s.accel_g[1] = 0.0f;
    s.accel_g[2] = 1.5f;
    return s;
}

void feedSecond(signal::SignalProcessor& p, TimeMs base_ms, float pulse_amplitude, float freq_hz,
                bool saturated = false, bool motion = false, float dc_ir = kTestDcIr) {
    PpgSample ppg[100];
    for (uint32_t i = 0; i < 100; ++i) {
        ppg[i] = mkPpg(base_ms + i * signal::kPpgSamplePeriodMs, pulse_amplitude, freq_hz,
                       saturated, dc_ir);
    }
    p.feedPpg(ppg, 100);
    ImuSample imu[50];
    for (uint32_t i = 0; i < 50; ++i) {
        const TimeMs t = base_ms + i * signal::kImuSamplePeriodMs;
        imu[i] = motion ? mkMotionImu(t) : mkQuietImu(t);
    }
    p.feedImu(imu, 50);
}

// DoD §14 evidence: prints one row of the synthetic-HR accuracy table so the
// numbers recorded in the spec's status log can be regenerated by re-running
// the suite (table lives in the spec, not in assertions alone).
void printHrAccuracyRow(float expected_bpm, const signal::SignalWindowOutput& out) {
    printf("[F02 DoD] expected %.0f bpm | measured %.2f bpm | err %+.2f | sqi %.3f | "
           "conf %.3f | valid %d | quality %d\n",
           expected_bpm, out.ppg.hr_bpm, out.ppg.hr_bpm - expected_bpm, out.ppg.sqi,
           out.ppg.hr_confidence, static_cast<int>(out.ppg.hr_valid),
           static_cast<int>(out.ppg.quality));
}

// Closes windows the way the 1 s ProcessingTask would after feeding this
// second (now is past window_end + kMaxSampleGapMs).
void closeDueWindows(signal::SignalProcessor& p, TimeMs now_ms, signal::SignalWindowOutput& last,
                     int& closed) {
    signal::SignalWindowOutput out{};
    while (p.step(now_ms, out)) {
        last = out;
        ++closed;
    }
}

