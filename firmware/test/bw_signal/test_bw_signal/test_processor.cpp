    TEST_ASSERT_TRUE(missed.valid);  // tolerant fraction 11/11
    TEST_ASSERT_TRUE(missed.consistency < signal::kMinIbiConsistencyFraction);  // 6/11 strict
    TEST_ASSERT_TRUE(missed.consistency_miss_tolerant >= signal::kMinIbiConsistencyFraction);
    TEST_ASSERT_FLOAT_WITHIN(3.0f, 100.0f, missed.hr_bpm);

    // (c) arrhythmia: IBIs alternating 500 / 1500 ms.
    beats.clear();
    t = 10;
    (void)beats.push(t);
    for (uint32_t i = 0; i < 9; ++i) {
        t += (i % 2u == 0u) ? 1500 : 500;
        (void)beats.push(t);
    }
    signal::HeartRateResult arrhythmia = signal::HeartRateEstimator::estimate(beats, 10000);
    TEST_ASSERT_FALSE(arrhythmia.valid);
    TEST_ASSERT_TRUE(arrhythmia.consistency_miss_tolerant < signal::kMinIbiConsistencyFraction);
