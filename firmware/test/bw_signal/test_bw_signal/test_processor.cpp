void test_processor_hr_survives_amplitude_jitter() {  // FIX loop 4 (bench round 7): steady contact,
                                                      // HR read correctly at first,
    // then dropped to "--" periodically and returned 10–20 s later. Root
    // cause: the adaptive threshold THR = 0.5 × amp_ema_ is a RATCHET —
    // amp_ema_ updates only on accepted beats, real beat amplitudes vary
    // 30–100 % beat-to-beat, so weak real beats fall below 0.5 × the recent
    // amplitude, are missed, IBI consistency collapses (hr_valid → "--"),
    // and only the 10 s starvation re-seed restores detection until a
    // strong beat reinflates the EMA. Fixture: DC 160 000, 70 bpm, beat
    // amplitude alternating 1800 / 600 counts (±50 % about the 1200 mean —
    // deterministic per-second modulation, no RNG), 60 s, quiet IMU. The
    // invariant: a jittered-but-regular train must keep hr_valid in ≥95 %
    // of windows with the correct median bpm — no starvation episodes.
    signal::SignalProcessor p;
    signal::SignalWindowOutput last{};
    int closed = 0;
    int valid_windows = 0;
    for (int sec = 0; sec < 60; ++sec) {
        const TimeMs base = static_cast<TimeMs>(sec) * signal::kMotionWindowMs;
        const float amp = (sec % 2 == 0) ? kJitterAmpHigh : kJitterAmpLow;
        const int before = closed;
        feedSecond(p, base, amp, 70.0f / 60.0f, /*saturated=*/false, /*motion=*/false, kJitterDcIr);
        closeDueWindows(p, base + signal::kMotionWindowMs + signal::kMaxSampleGapMs, last, closed);
        if (closed > before && last.ppg.hr_valid) {
            ++valid_windows;
        }
    }
    TEST_ASSERT_TRUE(closed >= 57);
    // ≥95 % of windows valid (integer form: no float rounding games).
    TEST_ASSERT_TRUE(valid_windows * 100 >= closed * 95);
    TEST_ASSERT_TRUE(last.ppg.hr_valid);
    TEST_ASSERT_FLOAT_WITHIN(3.0f, 70.0f, last.ppg.hr_bpm);
}

