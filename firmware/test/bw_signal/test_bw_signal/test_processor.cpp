    TEST_ASSERT_TRUE(clean.valid);
    TEST_ASSERT_FLOAT_WITHIN(0.01f, 1.0f, clean.consistency);
    TEST_ASSERT_FLOAT_WITHIN(0.01f, 1.0f, clean.consistency_miss_tolerant);
    TEST_ASSERT_FLOAT_WITHIN(3.0f, 70.6f, clean.hr_bpm);

    // (b) 45 % missed: alternating 600 / 1200 ms IBIs (one pulse in two
    // dipped below the floor) — SIX singles + FIVE doubles so the median
    // lands on the 600 ms cluster, bpm 100.
    beats.clear();
