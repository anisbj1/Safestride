#!/usr/bin/env python3
"""Design the F02 PPG filter chain and emit bw/signal/ppg_filter_coeffs.h.

Run:  python tools/design_ppg_filter.py   (writes ../include/bw/signal/ppg_filter_coeffs.h)

Why this exists (F02 D3/D7, DoD §14): the biquad coefficients are derived
offline from documented formulas so no magic numbers live in firmware, and the
derivation is reproducible instead of copied from a forum post.

Formulas: Robert Bristow-Johnson, "Audio EQ Cookbook" (RBJ biquad equations),
bilinear-transformed from the analog prototype. A 2nd-order Butterworth
section has Q = 1/sqrt(2) (maximally flat passband); cascading
high-pass(0.05) x high-pass(0.5) x low-pass(4.0) at fs = 100 Hz yields the
DC blocker + 0.5-4 Hz band-pass specified in F02 D3 (30-240 bpm).

Python standard library only (F00 §7.3: reproducible, no cleverness).
"""

import math
import os

FS_HZ = 100.0  # [DERIVED] 01 §3.3: PPG sampled at 100 Hz
TESTER_FS_HZ = 25.0  # [DERIVED] tester: 100 conversions/s / 4-sample averaging
Q_BUTTERWORTH = 1.0 / math.sqrt(2.0)  # 2nd-order Butterworth section

# (name, type, freq Hz) — matches kPpgDcBlockerHz/kPpgBandpassLowHz/HighHz
SECTIONS = [
    ("kPpgDcBlockerCoeffs", "highpass", 0.05),  # [DERIVED] F02 D7
    ("kPpgBandpassHighpassCoeffs", "highpass", 0.5),  # [DERIVED] F02 §8
    ("kPpgBandpassLowpassCoeffs", "lowpass", 4.0),  # [DERIVED] F02 §8
]


def biquad(kind: str, f0_hz: float, q: float, fs_hz: float):
    """Return (b0, b1, b2, a0, a1, a2) for one RBJ cookbook section."""
    w0 = 2.0 * math.pi * f0_hz / fs_hz
    cos_w0 = math.cos(w0)
    sin_w0 = math.sin(w0)
    alpha = sin_w0 / (2.0 * q)

    if kind == "lowpass":
        b0 = (1.0 - cos_w0) / 2.0
        b1 = 1.0 - cos_w0
        b2 = (1.0 - cos_w0) / 2.0
        a0 = 1.0 + alpha
        a1 = -2.0 * cos_w0
        a2 = 1.0 - alpha
    elif kind == "highpass":
        b0 = (1.0 + cos_w0) / 2.0
        b1 = -(1.0 + cos_w0)
        b2 = (1.0 + cos_w0) / 2.0
        a0 = 1.0 + alpha
        a1 = -2.0 * cos_w0
        a2 = 1.0 - alpha
    else:
        raise ValueError(f"unknown section kind: {kind}")
    return b0, b1, b2, a0, a1, a2


def normalize(coefs):
    b0, b1, b2, a0, a1, a2 = coefs
    return b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0


def response(coefs, f_hz: float, fs_hz: float) -> float:
    """|H(e^jw)| of one normalized section at f_hz (for the sanity table)."""
    b0, b1, b2, a1, a2 = coefs
    w = 2.0 * math.pi * f_hz / fs_hz
    num = (
        b0
        + b1 * math.cos(w)
        + b2 * math.cos(2 * w)
        + 1j * (b1 * math.sin(w) + b2 * math.sin(2 * w))
    )
    den = (
        1.0
        + a1 * math.cos(w)
        + a2 * math.cos(2 * w)
        + 1j * (a1 * math.sin(w) + a2 * math.sin(2 * w))
    )
    return abs(num) / abs(den)


def emit_header(path: str, normalized) -> None:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/design_ppg_filter.py — do not edit by hand.",
        "// Re-run the script after changing kPpgDcBlockerHz / kPpgBandpassLowHz /",
        "// kPpgBandpassHighHz / kPpgSamplePeriodMs in signal_config.h.",
        "//",
        "// Derivation: RBJ Audio EQ Cookbook bilinear biquads, 2nd-order",
        "// Butterworth sections (Q = 1/sqrt(2)) at fs = 100 Hz. Order of the",
        "// chain (F02 §7): DC blocker, band-pass high-pass, band-pass low-pass.",
        "// Normalized: a0 divided out (firmware stores a1, a2 only).",
        "",
        "#include <bw/signal/signal_config.h>",
        "",
        "namespace bw::signal {",
        "",
        "struct BiquadCoeffs {",
        "    float b0;",
        "    float b1;",
        "    float b2;",
        "    float a1;",
        "    float a2;",
        "};",
        "",
    ]
    for (name, kind, freq), coefs in zip(SECTIONS, normalized):
        b0, b1, b2, a1, a2 = coefs
        lines += [
            f"// {kind} f0 = {freq} Hz, Q = {Q_BUTTERWORTH:.6f}, fs = {FS_HZ:.0f} Hz",
            "// (RBJ cookbook; see tools/design_ppg_filter.py for the derivation).",
            f"inline constexpr BiquadCoeffs {name}{{",
            f"    {b0:.9e}f, {b1:.9e}f, {b2:.9e}f, {a1:.9e}f, {a2:.9e}f}};",
            "",
        ]
    for name, kind, freq in SECTIONS:
        b0, b1, b2, a1, a2 = normalize(biquad(kind, freq, Q_BUTTERWORTH, TESTER_FS_HZ))
        lines += [
            f"// [DERIVED] RBJ {kind} {freq} Hz at tester FIFO rate {TESTER_FS_HZ} Hz.",
            f"inline constexpr BiquadCoeffs {name}Tester{{",
            f"    {b0:.9e}f, {b1:.9e}f, {b2:.9e}f, {a1:.9e}f, {a2:.9e}f}};",
            "",
        ]
    lines += [
        "// Static checks: the DC blocker and the band-pass high-pass must have",
        "// (near) zero DC gain (b0+b1+b2 ~= 0) or the filter would shift the",
        "// baseline it is supposed to remove; 1e-6 covers float32 rounding of",
        "// the a0 normalization only.",
        "static_assert(kPpgDcBlockerCoeffs.b0 + kPpgDcBlockerCoeffs.b1 +",
        "                      kPpgDcBlockerCoeffs.b2 <",
        "                  1.0e-6f &&",
        "              kPpgDcBlockerCoeffs.b0 + kPpgDcBlockerCoeffs.b1 +",
        "                      kPpgDcBlockerCoeffs.b2 >",
        "                  -1.0e-6f);",
        "static_assert(kPpgBandpassHighpassCoeffs.b0 +",
        "                      kPpgBandpassHighpassCoeffs.b1 +",
        "                      kPpgBandpassHighpassCoeffs.b2 <",
        "                  1.0e-6f &&",
        "              kPpgBandpassHighpassCoeffs.b0 +",
        "                      kPpgBandpassHighpassCoeffs.b1 +",
        "                      kPpgBandpassHighpassCoeffs.b2 >",
        "                  -1.0e-6f);",
        "",
        "}  // namespace bw::signal",
        "",
    ]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def main() -> None:
    normalized = [
        normalize(biquad(kind, f0, Q_BUTTERWORTH, FS_HZ)) for (_, kind, f0) in SECTIONS
    ]

    header_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..",
        "include",
        "bw",
        "signal",
        "ppg_filter_coeffs.h",
    )
    emit_header(header_path, normalized)

    # Sanity table: corner frequencies must sit at -3 dB in the cascade
    # (Butterworth definition), passband ~0 dB.
    probe_hz = [0.05, 0.1, 0.5, 1.0, 2.0, 4.0, 8.0]
    print(f"{'f (Hz)':>8} {'|H| cascade':>12} {'dB':>8}")
    for f in probe_hz:
        gain = math.prod(response(c, f, FS_HZ) for c in normalized)
        db = 20.0 * math.log10(gain)
        print(f"{f:8.2f} {gain:12.4f} {db:8.2f}")
    corner_lo = math.prod(response(c, 0.5, FS_HZ) for c in normalized)
    corner_hi = math.prod(response(c, 4.0, FS_HZ) for c in normalized)
    assert abs(20 * math.log10(corner_lo) + 3.0) < 0.2, "low corner not at -3 dB"
    assert abs(20 * math.log10(corner_hi) + 3.0) < 0.2, "high corner not at -3 dB"
    print("corners at -3 dB: OK")


if __name__ == "__main__":
    main()
