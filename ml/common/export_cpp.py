"""Deterministic C++ header generation for F05 (D8: location, fidelity, staleness).

Emits three kinds of checked-in generated files:

- ``firmware/lib/bw_ml/include/bw/ml/feature_schema_v<N>.h``  (N = schema id)
- ``firmware/lib/bw_ml/include/bw/ml/model_<name>_v<N>.h``    (N = model_version)
- ``firmware/test/bw_ml/test_bw_ml/fixture_cases.h``          (oracle expectations)

Every emission is byte-stable: no timestamps, no machine-specific paths (only
file basenames appear in comments), fixed ordering, ``\\n`` newlines. ``python
ml/common/export_cpp.py check`` regenerates everything and byte-compares it
against the checked-in files — that is the staleness gate D8 requires (run by
``pytest ml/common/tests`` and usable by hand).
"""

import argparse
import json
import struct
import sys
from pathlib import Path
from typing import Iterable

from reference import (
    K_LEAF_FLAG,
    K_MAX_CLASSES,
    K_MAX_MODEL_BYTES,
    FlatTree,
    LinearModel,
    Model,
    TreeModel,
    confidence_of,
    contributions,
    load_model,
    predict,
)
from schema import K_MAX_FEATURES, FeatureSchema, load_schema

# Repo layout (machine-independent: derived from this file, never from cwd).
REPO_ROOT = Path(__file__).resolve().parents[2]
SCHEMAS_DIR = REPO_ROOT / "ml" / "common" / "schemas"
MODELS_DIR = REPO_ROOT / "ml" / "common" / "models"
CASES_PATH = REPO_ROOT / "ml" / "common" / "tests" / "predict_cases.json"
GENERATED_DIR = REPO_ROOT / "firmware" / "lib" / "bw_ml" / "include" / "bw" / "ml"
FIXTURE_HEADER_PATH = REPO_ROOT / "firmware" / "test" / "bw_ml" / "test_bw_ml" / "fixture_cases.h"
# Limits the byte accounting must mirror; test_export.py parses the header and fails on drift.
MODEL_LIMITS_HEADER = GENERATED_DIR / "model_limits.h"

# C++ layout of the generated constant arrays, used for the kModelBytes budget
# [DERIVED]: TreeNode {uint16, float, uint16, uint16} -> 2 + 2 pad + 4 + 2 + 2 = 12;
# TreeLeaf {float p[8]} = 32; TreeView {4 x uint16} = 8. The generated header
# static_asserts kModelBytes == sum of sizeof(...), so any drift fails every build.
K_TREE_NODE_BYTES = 12
K_TREE_LEAF_BYTES = K_MAX_CLASSES * 4
K_TREE_VIEW_BYTES = 8
K_FLOAT_BYTES = 4

_GENERATE_CMD = "python ml/common/export_cpp.py all"


def float32_lit(value: float) -> str:
    """Shortest C++ literal that round-trips to the same float32 (D8 fidelity).

    Equals D8's ``repr(float(np.float32(v)))`` but uses stdlib ``struct`` only:
    ``ml/pyproject.toml`` declares no numpy dependency and F05 does not own that
    file [ASSUMED] — the resulting literal is bit-identical either way.
    """
    rounded = struct.unpack("f", struct.pack("f", float(value)))[0]
    text = repr(rounded)
    if not any(c in text for c in ".eE"):  # pragma: no cover - repr always has one
        text += ".0"
    return text + "f"


def _float_array(name: str, values: Iterable[float], indent: str = "") -> list[str]:
    """Emit a constexpr float array, 4 values per line (deterministic wrapping)."""
    lits = [float32_lit(v) for v in values]
    if not lits:
        return [f"{indent}constexpr float {name}[] = {{}};"]
    lines = [f"{indent}constexpr float {name}[] = {{"]
    for start in range(0, len(lits), 4):
        chunk = ", ".join(lits[start : start + 4])
        suffix = "," if start + 4 < len(lits) else ""
        lines.append(f"{indent}    {chunk}{suffix}")
    lines.append(f"{indent}}};")
    return lines


def _str_array(name: str, values: list[str], indent: str = "") -> list[str]:
    joined = ", ".join(f'"{v}"' for v in values)
    return [f"{indent}constexpr const char* {name}[] = {{{joined}}};"]


# The emitted layout (4 values per line, fixed wrapping) is part of the D8
# byte-stable contract: `export_cpp.py check` byte-compares it, so the repo
# format gate must never re-wrap it. Standard practice for generated files:
# guard the content with clang-format off/on instead of reformatting output.
FORMAT_GUARD_OFF = "// clang-format off"
FORMAT_GUARD_ON = "// clang-format on"


def _generated_banner(source_files: list[str]) -> list[str]:
    sources = " ".join(source_files)
    return [
        "// GENERATED by ml/common/export_cpp.py - DO NOT EDIT BY HAND.",
        f"// Source: {sources}",
        f"// Regenerate: {_GENERATE_CMD}   (staleness gate: pytest ml/common/tests)",
        "// Contract: docs/contracts/FEATURE_SCHEMA.md sections 2.2-2.3 (F05 D2/D4/D8).",
        FORMAT_GUARD_OFF,
        "// Emitted layout is byte-stable (D8) and byte-compared by export_cpp.py check,",
        "// so clang-format must not re-wrap the constants below.",
    ]


def generate_schema_header(schema: FeatureSchema, source_name: str) -> bytes:
    """Emit ``feature_schema_v<id>.h`` — constants the composition root injects (D4)."""
    namespace = f"schema_v{schema.schema_id}"
    lines = _generated_banner([source_name])
    lines += [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "#include <bw/model.h>  // bw::kMaxFeatures",
        "",
        f"namespace bw::ml::{namespace} {{",
        "",
        "// Handshake values a FeatureVector must carry for this schema (section 3).",
        f"constexpr uint16_t kSchemaId = {schema.schema_id};",
        f"constexpr uint16_t kSchemaVersion = {schema.schema_version};",
        f"constexpr uint8_t kFeatureCount = {schema.feature_count};",
        'static_assert(kFeatureCount <= bw::kMaxFeatures, "schema exceeds bw::kMaxFeatures");',
        "",
        "// Feature order is normative: array index = FeatureVector position (section 2.1).",
    ]
    lines += _str_array("kFeatureNames", [f.name for f in schema.features])
    lines += [
        "// Normative normalization: x' = (x - kFeatureMean[i]) / kFeatureStd[i] (section 4).",
        '// method "none" is re-written to identity (mean 0, std 1) at generation (D4).',
    ]
    lines += _float_array("kFeatureMean", [f.mean for f in schema.features])
    lines += _float_array("kFeatureStd", [f.std for f in schema.features])
    lines += ["", f"}}  // namespace bw::ml::{namespace}", FORMAT_GUARD_ON, ""]
    return "\n".join(lines).encode("utf-8")


def model_byte_size(model: Model) -> int:
    """Byte cost of the numeric constant arrays (pointers/strings excluded, D8)."""
    if isinstance(model, LinearModel):
        return (model.n_classes * model.feature_count + model.n_classes) * K_FLOAT_BYTES
    assert isinstance(model, TreeModel)
    nodes = sum(len(tree.nodes) for tree in model.trees)
    leaves = sum(len(tree.leaves) for tree in model.trees)
    return (
        nodes * K_TREE_NODE_BYTES
        + leaves * K_TREE_LEAF_BYTES
        + len(model.trees) * K_TREE_VIEW_BYTES
    )


def _descriptor_init(model: Model) -> str:
    fields = [
        f'"{model.name}"',
        str(model.model_version),
        str(model.schema_id),
        str(model.schema_version),
        str(model.n_classes),
        "kClassNames",
        f'"{model.training_data_hash}"',
    ]
    return "    ModelDescriptor{" + ", ".join(fields) + "};"


def _byte_budget_lines(model: Model, size_terms: str) -> list[str]:
    if model_byte_size(model) > K_MAX_MODEL_BYTES:
        raise ValueError(
            f"model {model.name}: {model_byte_size(model)} bytes exceeds "
            f"kMaxModelBytes = {K_MAX_MODEL_BYTES} (F05 section 8)"
        )
    return [
        "",
        "// Exporter-computed size of the numeric constant arrays (bytes); pointers and",
        "// strings excluded - they are target-dependent (D8 / section 8).",
        f"constexpr size_t kModelBytes = {model_byte_size(model)};",
        "static_assert(kModelBytes <= kMaxModelBytes,"
        ' "model exceeds kMaxModelBytes (F05 section 8)");',
        f"static_assert(kModelBytes == {size_terms},",
        '              "exporter byte accounting differs from the compiled layout");',
    ]


def generate_model_header(model: Model, source_name: str) -> bytes:
    """Emit ``model_<name>_v<version>.h`` — weights/trees + descriptor + budget (§7)."""
    namespace = model.name
    lines = _generated_banner([source_name])
    lines += ["#pragma once", "", "#include <cstddef>", "#include <cstdint>", ""]
    if isinstance(model, LinearModel):
        lines.append("#include <bw/ml/model_descriptor.h>")
        lines.append("#include <bw/ml/model_limits.h>")
        lines.append("#include <bw/ml/model_linear.h>")
    else:
        lines.append("#include <bw/ml/model_descriptor.h>")
        lines.append("#include <bw/ml/model_limits.h>")
        lines.append("#include <bw/ml/model_tree.h>")
    lines += [
        "",
        f"namespace bw::ml::{namespace} {{",
        "",
        "// Class order is normative: index = ModelOutput::p position.",
    ]
    lines += _str_array("kClassNames", list(model.classes))
    if isinstance(model, LinearModel):
        lines += [
            "// Row-major weights [class][feature]; bias [class] (D7).",
        ]
        weights = [w for row in model.weights for w in row]
        lines += _float_array("kWeights", weights)
        lines += _float_array("kBias", model.bias)
        lines += [
            "constexpr ModelDescriptor kDescriptor =",
            _descriptor_init(model),
            "constexpr LinearModelData kModel = LinearModelData{kWeights, kBias, "
            f"{model.feature_count}, kDescriptor}};",
        ]
        lines += _byte_budget_lines(model, "sizeof(kWeights) + sizeof(kBias)")
    else:
        assert isinstance(model, TreeModel)
        lines += [
            "// Flat arrays, pre-order per tree (root = node 0); child reference with",
            f"// bit 15 set ({K_LEAF_FLAG}) is a leaf index, otherwise a node index (D6).",
        ]
        lines += _tree_arrays(model.trees)
        lines += [
            "constexpr ModelDescriptor kDescriptor =",
            _descriptor_init(model),
            "constexpr TreeModelData kModel = TreeModelData{kNodes, kLeaves, kTreeViews, "
            f"{sum(len(t.nodes) for t in model.trees)}, "
            f"{sum(len(t.leaves) for t in model.trees)}, "
            f"{len(model.trees)}, {model.feature_count}, kDescriptor}};",
        ]
        lines += _byte_budget_lines(model, "sizeof(kNodes) + sizeof(kLeaves) + sizeof(kTreeViews)")
    lines += ["", f"}}  // namespace bw::ml::{namespace}", FORMAT_GUARD_ON, ""]
    return "\n".join(lines).encode("utf-8")


def _tree_arrays(trees: tuple[FlatTree, ...]) -> list[str]:
    lines: list[str] = []
    # TreeNode{feature, threshold, left, right} — field order is normative (D6).
    lines.append("constexpr TreeNode kNodes[] = {")
    for tree in trees:
        for node in tree.nodes:
            left = (
                f"leafRef({node.left & ~K_LEAF_FLAG})"
                if node.left & K_LEAF_FLAG
                else str(node.left)
            )
            right = (
                f"leafRef({node.right & ~K_LEAF_FLAG})"
                if node.right & K_LEAF_FLAG
                else str(node.right)
            )
            lines.append(
                f"    TreeNode{{{node.feature}, {float32_lit(node.threshold)}, {left}, {right}}},"
            )
    lines.append("};")
    lines.append("")
    lines.append("// Leaf probability rows: [class], padded to kMaxModelClasses with 0.")
    lines.append("constexpr TreeLeaf kLeaves[] = {")
    for tree in trees:
        for leaf in tree.leaves:
            padded = list(leaf) + [0.0] * (K_MAX_CLASSES - len(leaf))
            rows = ", ".join(float32_lit(v) for v in padded)
            lines.append(f"    TreeLeaf{{{{{rows}}}}},")
    lines.append("};")
    lines.append("")
    lines.append(
        "// Per-tree offsets into kNodes/kLeaves:"
        " {node_offset, node_count, leaf_offset, leaf_count}."
    )
    lines.append("constexpr TreeView kTreeViews[] = {")
    node_offset = 0
    leaf_offset = 0
    for tree in trees:
        lines.append(
            f"    TreeView{{{node_offset}, {len(tree.nodes)}, {leaf_offset}, {len(tree.leaves)}}},"
        )
        node_offset += len(tree.nodes)
        leaf_offset += len(tree.leaves)
    lines.append("};")
    lines.append("")
    return lines


# --------------------------------------------------------------------------
# Fixture header: oracle expectations the host suite asserts against (§9).
# --------------------------------------------------------------------------


def load_cases(path: Path = CASES_PATH) -> list[dict[str, object]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not isinstance(data.get("cases"), list):
        raise ValueError(f"{path}: expected an object with a 'cases' array")
    return data["cases"]


def case_expectation(model: Model, x: list[float]) -> dict[str, object]:
    """Run the oracle for one fixture case (FEATURE_SCHEMA.md section 4 semantics)."""
    probabilities = predict(model, x)
    supported = isinstance(model, LinearModel)
    weighted = contributions(model, x) if supported else []
    return {
        "schema_id": model.schema_id,
        "schema_version": model.schema_version,
        "count": model.feature_count,
        "n_classes": model.n_classes,
        "p": probabilities,
        "confidence": confidence_of(probabilities),
        "contributions_supported": supported,
        "contributions": [value for _, value in weighted],
    }


def _pad(values: list[float], size: int, label: str) -> list[float]:
    if len(values) > size:
        raise ValueError(f"{label}: {len(values)} values exceed {size}")
    return list(values) + [0.0] * (size - len(values))


def generate_fixture_header(models: dict[str, Model], cases: list[dict[str, object]]) -> bytes:
    """Emit ``fixture_cases.h`` — inputs + oracle outputs for the host suite."""
    lines = _generated_banner(["predict_cases.json"])
    lines += [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "#include <bw/model.h>",
        "",
        "// One oracle-checked fixture case: input FeatureVector values plus the",
        "// predictions ml/common/reference.py produced for them (F05 section 9).",
        "namespace bw_ml_fixture {",
        "",
        "struct PredictCase {",
        "    const char* model;      // factory key for models_under_test.h",
        "    uint16_t schema_id;",
        "    uint16_t schema_version;",
        "    uint8_t count;",
        "    uint8_t n_classes;",
        "    float v[bw::kMaxFeatures];",
        "    float p[bw::kMaxModelClasses];",
        "    float confidence;",
        "    bool contributions_supported;",
        "    uint8_t n_contributions;",
        "    float contributions[bw::kMaxFeatures];",
        "};",
        "",
        "constexpr PredictCase kPredictCases[] = {",
    ]
    for case in cases:
        name = case.get("model")
        if not isinstance(name, str) or name not in models:
            raise ValueError(f"predict_cases: unknown model {name!r}")
        model = models[name]
        raw_x = case.get("v")
        if not isinstance(raw_x, list) or len(raw_x) != model.feature_count:
            raise ValueError(
                f"predict_cases case for {name}: v must hold exactly "
                f"{model.feature_count} finite numbers"
            )
        x = [float(value) for value in raw_x]
        expected = case_expectation(model, x)
        v = _pad(x, K_MAX_FEATURES, f"case v for {name}")
        p = _pad(expected["p"], K_MAX_CLASSES, f"case p for {name}")
        contrib = _pad(expected["contributions"], K_MAX_FEATURES, f"case contributions for {name}")
        # Brace-heavy output: plain concatenation keeps the emitted braces
        # unambiguous (an f-string escaping mistake here is easy to miss).
        v_lit = ", ".join(float32_lit(value) for value in v)
        p_lit = ", ".join(float32_lit(value) for value in p)
        c_lit = ", ".join(float32_lit(value) for value in contrib)
        supported = "true" if expected["contributions_supported"] else "false"
        lines.append('    PredictCase{"' + name + '",')
        lines.append(
            f"        {expected['schema_id']}, {expected['schema_version']}, "
            f"{expected['count']}, {expected['n_classes']},"
        )
        lines.append("        {" + v_lit + "},")
        lines.append("        {" + p_lit + "},")
        lines.append(f"        {float32_lit(expected['confidence'])},")
        lines.append(f"        {supported}, {len(expected['contributions'])},")
        lines.append("        {" + c_lit + "}},")
    lines += [
        "};",
        "",
        "constexpr size_t kPredictCaseCount = sizeof(kPredictCases) / sizeof(kPredictCases[0]);",
        "",
        "}  // namespace bw_ml_fixture",
        FORMAT_GUARD_ON,
        "",
    ]
    return "\n".join(lines).encode("utf-8")


# --------------------------------------------------------------------------
# Orchestration: every checked-in generated file, in deterministic order.
# --------------------------------------------------------------------------


def _load_all_schemas() -> dict[int, FeatureSchema]:
    schemas = {}
    for path in sorted(SCHEMAS_DIR.glob("feature_schema_*.json")):
        schema = load_schema(path)
        expected = f"feature_schema_v{schema.schema_id}.json"
        if path.name != expected:
            raise ValueError(f"{path.name}: file name must be {expected} (N = schema_id)")
        schemas[schema.schema_id] = schema
    if not schemas:
        raise ValueError(f"{SCHEMAS_DIR}: no feature_schema_*.json found")
    return schemas


def _load_all_models() -> dict[str, Model]:
    models = {}
    for path in sorted(MODELS_DIR.glob("model_*.json")):
        model = load_model(path)
        expected = f"model_{model.name}_v{model.model_version}.json"
        if path.name != expected:
            raise ValueError(f"{path.name}: file name must be {expected}")
        models[model.name] = model
    if not models:
        raise ValueError(f"{MODELS_DIR}: no model_*.json found")
    return models


def _cross_check_schema(model: Model, schemas: dict[int, FeatureSchema], source: str) -> None:
    schema = schemas.get(model.schema_id)
    if schema is None:
        raise ValueError(f"{source}: references unknown schema_id {model.schema_id}")
    if schema.schema_version != model.schema_version:
        raise ValueError(
            f"{source}: schema_version {model.schema_version} does not match "
            f"schema file version {schema.schema_version}"
        )
    if schema.feature_count != model.feature_count:
        raise ValueError(
            f"{source}: feature_count {model.feature_count} does not match "
            f"schema feature count {schema.feature_count}"
        )


def iter_artifacts() -> list[tuple[Path, bytes]]:
    """All generated files as (path, bytes), in deterministic (sorted) order."""
    schemas = _load_all_schemas()
    models = _load_all_models()
    artifacts: list[tuple[Path, bytes]] = []
    for schema_id in sorted(schemas):
        schema = schemas[schema_id]
        artifacts.append(
            (
                GENERATED_DIR / f"feature_schema_v{schema_id}.h",
                generate_schema_header(schema, f"feature_schema_v{schema_id}.json"),
            )
        )
    for name in sorted(models):
        model = models[name]
        _cross_check_schema(model, schemas, f"model {name}")
        artifacts.append(
            (
                GENERATED_DIR / f"model_{name}_v{model.model_version}.h",
                generate_model_header(model, f"model_{name}_v{model.model_version}.json"),
            )
        )
    artifacts.append((FIXTURE_HEADER_PATH, generate_fixture_header(models, load_cases())))
    return artifacts


def write_all() -> list[Path]:
    written = []
    for path, data in iter_artifacts():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written.append(path)
    return written


def check_all() -> list[str]:
    """Return a description per stale/missing generated file (empty = fresh)."""
    problems = []
    for path, expected in iter_artifacts():
        rel = path.relative_to(REPO_ROOT).as_posix()
        if not path.exists():
            problems.append(f"missing: {rel}")
        elif path.read_bytes() != expected:
            problems.append(f"stale: {rel}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="export_cpp.py", description="Generate F05 checked-in C++ headers (D8)."
    )
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("all", help="regenerate every generated header")
    sub.add_parser("check", help="byte-compare generated headers against the repo (staleness gate)")
    args = parser.parse_args(argv)
    try:
        if args.command == "all":
            for path in write_all():
                print(f"wrote {path.relative_to(REPO_ROOT).as_posix()}")
            return 0
        problems = check_all()
    except (ValueError, OSError) as exc:
        print(f"export_cpp: {exc}", file=sys.stderr)
        return 2
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        print(f"run: {_GENERATE_CMD}", file=sys.stderr)
        return 1
    print("all generated headers are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
